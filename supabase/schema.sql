-- StudyMate database schema
-- Run this in Supabase Dashboard -> SQL Editor -> New query -> Run

create table public.study_plans (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  subject text not null,
  topic text not null,
  notes text default '',
  is_completed boolean default false,
  created_at timestamptz default now()
);

-- Turn on Row Level Security
alter table public.study_plans enable row level security;

-- SELECT: students can only see their own study plans
create policy "Students can view their own study plans"
on public.study_plans
for select
using (auth.uid() = student_id);

-- INSERT: students can only create study plans for themselves
create policy "Students can insert their own study plans"
on public.study_plans
for insert
with check (auth.uid() = student_id);

-- UPDATE: students can only update their own study plans
create policy "Students can update their own study plans"
on public.study_plans
for update
using (auth.uid() = student_id);

-- DELETE: students can only delete their own study plans
create policy "Students can delete their own study plans"
on public.study_plans
for delete
using (auth.uid() = student_id);
